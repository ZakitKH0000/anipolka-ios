"""Проверка IPA физического iPhone; подпись выполняет пользователь отдельно."""
import plistlib
import struct
import sys
import zipfile

with zipfile.ZipFile(sys.argv[1]) as z:
    root = 'Payload/AniPolka.app/'
    info = plistlib.loads(z.read(root + 'Info.plist'))
    assert info['CFBundleIdentifier'] == 'com.zakitkh.anipolka'
    assert info['CFBundleExecutable'] == 'AniPolka'
    assert info['CFBundleDisplayName'] == 'АниПолка'
    assert info['CFBundleSupportedPlatforms'] == ['iPhoneOS']
    assert info['UIDeviceFamily'] == [1]
    assert info['MinimumOSVersion'] == '17.0'
    assert info['CFBundleShortVersionString'] == '1.2.0'
    assert info['CFBundleVersion'] == '3'
    assert info['CFBundleURLTypes'][0]['CFBundleURLSchemes'] == ['anipolka']
    assert info['UIBackgroundModes'] == ['fetch']
    assert info['BGTaskSchedulerPermittedIdentifiers'] == ['com.zakitkh.anipolka.releases']
    b = z.read(root + 'AniPolka')
    assert b[:4] == b'\xcf\xfa\xed\xfe'
    assert struct.unpack_from('<I', b, 4)[0] == 0x0100000C, 'Expected ARM64'
    # LC_BUILD_VERSION platform must be iOS (2), not iOS simulator (7).
    offset, platforms = 32, []
    for _ in range(struct.unpack_from('<I', b, 16)[0]):
        cmd, size = struct.unpack_from('<II', b, offset)
        if cmd == 0x32:
            platforms.append(struct.unpack_from('<I', b, offset + 8)[0])
        offset += size
    assert platforms == [2], platforms
    assert root + 'Assets.car' in z.namelist()
    alternates = info.get('CFBundleIcons', {}).get('CFBundleAlternateIcons', {})
    assert {'AppIconLight', 'AppIconDonghua'} <= set(alternates), alternates
    widget = root + 'PlugIns/AniPolkaWidgets.appex/'
    winfo = plistlib.loads(z.read(widget + 'Info.plist'))
    assert winfo['CFBundleIdentifier'] == 'com.zakitkh.anipolka.widgets'
    assert winfo['NSExtension']['NSExtensionPointIdentifier'] == 'com.apple.widgetkit-extension'
    assert winfo['CFBundleShortVersionString'] == info['CFBundleShortVersionString']
    assert winfo['CFBundleVersion'] == info['CFBundleVersion']
    assert widget + 'AniPolkaWidgets' in z.namelist()
    # App Shortcuts metadata is generated by Xcode from the AppIntents code.
    assert any(n.startswith(root + 'Metadata.appintents/') for n in z.namelist()), 'App Intents metadata missing'
    assert not any(n.endswith(('.p12', '.mobileprovision')) for n in z.namelist())
    print('Проверено: АниПолка, ARM64 Mach-O, платформа iPhoneOS, иконка, виджет, действия «Команд», отдельный bundle ID, без signing secrets.')
